class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas for exact total page count in header/footer."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica-Bold", 8)
        self.setFillColor(colors.HexColor("#6E6D68"))

        # Top Running Header
        self.drawString(36, 810, "EKATUNGGAL GROUP (PT EKATUNGGAL TUNAS MANDIRI) // EXECUTIVE AUDIT")
        self.drawRightString(559, 810, "H1 2026 DISTRIBUTION RECONCILIATION // CONFIDENTIAL")
        self.setStrokeColor(colors.HexColor("#141413"))
        self.setLineWidth(0.5)
        self.line(36, 804, 559, 804)

        # Bottom Running Footer
        self.line(36, 36, 559, 36)
        self.setFont("Helvetica", 8)
        self.drawString(36, 24, "Generated by Analytics Engineering Pipeline — DuckDB v1.5.6 Storage Engine")
        page_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(559, 24, page_text)
        self.restoreState()


def format_idr(val):
    num = round(float(val or 0))
    if num < 0:
        return f"(Rp {abs(num):,})".replace(",", ".")
    return f"Rp {num:,}".replace(",", ".")


def format_millions(val):
    num = float(val or 0)
    if abs(num) >= 1_000_000_000:
        return f"{'-' if num < 0 else ''}Rp {abs(num)/1_000_000_000:.2f} M"
    if abs(num) >= 1_000_000:
        return f"{'-' if num < 0 else ''}Rp {abs(num)/1_000_000:.1f} Jt"
    return f"Rp {abs(num):,.0f}".replace(",", ".")


